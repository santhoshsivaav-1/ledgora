// Generates src/itr4Codes.ts from the official ITR-4 schema: the business codes (44AD, 44ADA), the TDS section codes and
// their sections, the other-sources nature codes. Run after adding a new schema to schemas/itr4/.
//   node scripts/gen-itr4-codes.mjs [schemas/itr4/AY2026-27.json]
import { readFileSync, writeFileSync } from 'node:fs';

const file = process.argv[2] ?? new URL('../schemas/itr4/AY2026-27.json', import.meta.url).pathname;
const schema = JSON.parse(readFileSync(file, 'utf8'));
const d = schema.definitions;

/** "01001 - Tea, 01002 - Coffee" → [{code, text}], checked against the enum so nothing is lost or invented. */
function described(prop, codeRe) {
  const re = new RegExp(`(${codeRe})\\s*-\\s*`, 'g');
  const text = prop.description ?? '';
  const marks = [...text.matchAll(re)];
  const out = new Map();
  marks.forEach((m, i) => {
    const end = i + 1 < marks.length ? marks[i + 1].index : text.length;
    out.set(
      m[1],
      text
        .slice(m.index + m[0].length, end)
        .replace(/[\s,;]+$/, '')
        .trim(),
    );
  });
  const missing = prop.enum.filter((c) => !out.has(c));
  if (missing.length)
    throw new Error(`no description for ${missing.length} codes: ${missing.slice(0, 5)}`);
  return prop.enum.map((c) => ({ code: c, text: out.get(c) }));
}
const ad = described(d.NatOfBus44AD.properties.CodeAD, '\\d{5}(?:_\\d)?');
const ada = described(d.NatOfBus44ADA.properties.CodeADA, '\\d{5}(?:_\\d)?');

// TDS sections: "92A:192- Salary…; 192A:192A/2AA- TDS on PF withdrawal; …"
const tdsProp = d.TDSonOthThanSalDtls.properties.TDSSection;
const tds = tdsProp.description
  .split(';')
  .map((s) => s.trim())
  .filter(Boolean)
  .map((s) => {
    const i = s.indexOf(':');
    const code = s.slice(0, i).trim();
    const rest = s.slice(i + 1).trim();
    const dash = rest.indexOf('-');
    return { code, section: rest.slice(0, dash).trim(), text: rest.slice(dash + 1).trim() };
  });
const known = new Set(tdsProp.enum);
const bad = tds.filter((t) => !known.has(t.code));
if (bad.length) throw new Error(`TDS codes not in the enum: ${bad.map((b) => b.code)}`);

const lit = (v) => JSON.stringify(v, null, 2);
const out = `// GENERATED by scripts/gen-itr4-codes.mjs from schemas/itr4/AY2026-27.json: do not edit by hand.
// The code lists of the official ITR-4 JSON schema (assessment year 2026-27), with the descriptions the schema carries.

export interface Itr4Code { code: string; text: string }
export interface Itr4TdsSection extends Itr4Code { section: string }

/** Business codes for presumptive business income, section 44AD. */
export const ITR4_CODES_44AD: readonly Itr4Code[] = ${lit(ad)};
/** Professions for presumptive income, section 44ADA. */
export const ITR4_CODES_44ADA: readonly Itr4Code[] = ${lit(ada)};
/** TDS section codes as the schema spells them (\`94C\` is section 194C, \`4H\` is 194H) with the section and what it is. */
export const ITR4_TDS_SECTIONS: readonly Itr4TdsSection[] = ${lit(tds)};
`;
writeFileSync(new URL('../src/itr4Codes.ts', import.meta.url), out);
console.log(
  `itr4Codes.ts: ${ad.length} business codes, ${ada.length} professions, ${tds.length} TDS sections`,
);
