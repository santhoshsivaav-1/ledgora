// Generates src/itr3Codes.ts from the official ITR-3 schema: the nature-of-business codes and the TDS section codes.
// Run after adding a new schema to schemas/itr3/.
//   node scripts/gen-itr3-codes.mjs [schemas/itr3/AY2026-27.json]
import { readFileSync, writeFileSync } from 'node:fs';

const file = process.argv[2] ?? new URL('../schemas/itr3/AY2026-27.json', import.meta.url).pathname;
const schema = JSON.parse(readFileSync(file, 'utf8'));
const d = schema.definitions;
const resolve = (n) => (n.$ref ? d[n.$ref.split('/').pop()] : n);

/** "01001 - Tea, 01002 - Coffee" → [{code, text}], checked against the enum so nothing is lost or invented. */
function described(prop, codeRe) {
  const re = new RegExp(`(${codeRe})\\s*-\\s*`, 'g');
  const text = prop.description ?? '';
  const marks = [...text.matchAll(re)];
  const out = new Map();
  marks.forEach((m, i) => {
    const end = i + 1 < marks.length ? marks[i + 1].index : text.length;
    out.set(m[1], text.slice(m.index + m[0].length, end).replace(/[\s,;]+$/, '').trim());
  });
  const missing = prop.enum.filter((c) => !out.has(c));
  if (missing.length) throw new Error(`no description for ${missing.length} codes: ${missing.slice(0, 5)}`);
  return prop.enum.map((c) => ({ code: c, text: out.get(c) }));
}

const nat = resolve(resolve(d.PartA_GEN2.properties.NatOfBus).properties.NatureOfBusiness.items).properties.Code;
const business = described(resolve(nat), '\\d{5}(?:_\\d)?');

const tdsItem = resolve(d.ScheduleTDS2.properties.TDSOthThanSalaryDtls.items);
const tdsProp = resolve(tdsItem.properties.TDSSection);
const tds = tdsProp.description
  .split(';')
  .map((s) => s.trim())
  .filter(Boolean)
  .map((s) => {
    const i = s.indexOf(':');
    const code = s.slice(0, i).trim();
    const rest = s.slice(i + 1).trim();
    const dash = rest.indexOf('-');
    return { code, section: rest.slice(0, dash).trim(), text: rest.slice(dash + 1).trim() };
  });
const known = new Set(tdsProp.enum);
const bad = tds.filter((t) => !known.has(t.code));
if (bad.length) throw new Error(`TDS codes not in the enum: ${bad.map((b) => b.code)}`);

const lit = (v) => JSON.stringify(v, null, 2);
writeFileSync(
  new URL('../src/itr3Codes.ts', import.meta.url),
  `// GENERATED by scripts/gen-itr3-codes.mjs from schemas/itr3/AY2026-27.json: do not edit by hand.
// The code lists of the official ITR-3 JSON schema (assessment year 2026-27), with the descriptions the schema carries.

export interface Itr3Code { code: string; text: string }
export interface Itr3TdsSection extends Itr3Code { section: string }

/** Nature-of-business codes (Part A General, nature of business). */
export const ITR3_BUSINESS_CODES: readonly Itr3Code[] = ${lit(business)};
/** TDS section codes as the schema spells them (\`94C\` is section 194C) with the section and what it is. */
export const ITR3_TDS_SECTIONS: readonly Itr3TdsSection[] = ${lit(tds)};
`,
);
console.log(`itr3Codes.ts: ${business.length} business codes, ${tds.length} TDS sections`);
