import {
  businessKeyOf,
  clientYearToDate,
  counterKeyFor,
  formatDocNumber,
  getFinancialYearLabel,
  localToday,
  nextCounterValue,
  numberSeriesFor,
  startFor,
  templateTotals,
} from '@ledgora/tax-engine';
import type { Tx } from '@ledgora/db';
import { AppError } from '../../errors.ts';
import { addDays, advanceDate } from '../recurring.ts';
import { META, bumpCounter, getDoc, getKv, listDocs, putDoc, allMeta, type Doc } from './store.ts';

type Rec = Record<string, any>; // eslint-disable-line @typescript-eslint/no-explicit-any -- templates are free-form documents

const PREFIX_BY_TYPE: Record<string, string> = {
  proforma: 'EST',
  quotation: 'QUO',
  'credit-note': 'CN',
  'bill-of-supply': 'BOS',
  composition: 'COMP',
  'delivery-challan': 'DC',
};

const hasEnded = (tpl: Rec, today: string) =>
  (tpl.endMode === 'onDate' && tpl.endDate && today > tpl.endDate) ||
  (tpl.endMode === 'afterN' &&
    tpl.maxOccurrences &&
    (tpl.occurrencesCreated || 0) >= tpl.maxOccurrences);

/** Takes the next invoice number of a business's series, the same rules as the invoice screen. */
async function nextInvoiceNumber(
  tx: Tx,
  orgId: string,
  prefix: string,
  invoiceType: string,
  businessKey: string,
) {
  const meta = await allMeta(tx);
  const series = numberSeriesFor(
    meta.invoiceNumberSettings as Rec,
    meta.invoiceNumberSeries as Rec,
    businessKey,
  );
  const key = counterKeyFor(prefix, series, businessKey);
  const next = await bumpCounter(tx, orgId, META + key, (cur) =>
    nextCounterValue(cur as number, startFor(invoiceType, series)),
  );
  return formatDocNumber({
    settings: series,
    typePrefix: prefix,
    next,
    fyLabel: getFinancialYearLabel(),
  });
}

/**
 * Makes ONE invoice from a recurring template and moves the template on ("Generate now"). A paused or not-yet-due
 * template still runs (the user asked), but not after it has ended. The daily scheduler arrives in change 6.7.
 */
export async function generateFromTemplate(tx: Tx, orgId: string, tpl: Rec) {
  const today = localToday();
  if (hasEnded(tpl, today))
    throw new AppError('conflict', 'This template has reached its end date or number of invoices');

  // The business this template bills for: the one it was assigned to, else its saved profile id or name, else the active one.
  const profiles = (await listDocs(tx, 'profiles')) as Rec[];
  const profile: Rec =
    profiles.find((p) => p.gstin && tpl.ownerGstin && p.gstin === tpl.ownerGstin) ||
    profiles.find((p) => p.id && tpl.profileId && p.id === tpl.profileId) ||
    profiles.find(
      (p) => p.businessName && p.businessName === (tpl.profileBusinessName || tpl.ownerName),
    ) ||
    ((await getKv<Rec>(tx, 'profile')) ?? {});

  const prefix = PREFIX_BY_TYPE[tpl.invoiceType] ?? 'INV';
  const bizKey = businessKeyOf(profile);
  // Never overwrite an existing invoice: if the counter lags behind the bills (restored backup, hand-typed numbers), take the next one.
  let invoiceNumber = await nextInvoiceNumber(tx, orgId, prefix, tpl.invoiceType, bizKey);
  for (let i = 0; i < 50 && (await getDoc(tx, 'bills', invoiceNumber)); i++)
    invoiceNumber = await nextInvoiceNumber(tx, orgId, prefix, tpl.invoiceType, bizKey);

  const bills = (await listDocs(tx, 'bills')) as Rec[];
  const ytd = clientYearToDate(bills, tpl.clientName, today);
  const totals = templateTotals(tpl, profile, {
    tcsCumulativeThisYear: ytd,
    tdsCumulativeThisYear: ytd,
  });
  const dueDays = Number(tpl.dueDays);
  const dueDate =
    Number.isFinite(dueDays) && dueDays >= 0 && tpl.dueDays !== '' && tpl.dueDays !== null
      ? addDays(today, dueDays)
      : '';
  const type = tpl.invoiceType || 'tax-invoice';

  const bill = {
    id: invoiceNumber,
    clientName: tpl.clientName,
    invoiceNumber,
    invoiceDate: today,
    invoiceType: type,
    currency: tpl.invoiceOptions?.currency || 'INR',
    totalAmount: totals.total,
    totalTaxAmount: totals.totalTaxAmount,
    status: 'unpaid',
    paidAmount: 0,
    payments: [],
    generatedFrom: tpl.id,
    autoGenerated: true,
    autoGeneratedAt: new Date().toISOString(),
    data: {
      profile,
      client: {
        name: tpl.clientName,
        state: tpl.clientState,
        gstin: tpl.clientGstin,
        address: tpl.clientAddress,
        country: tpl.clientCountry,
        city: tpl.clientCity,
        pin: tpl.clientPin,
        email: tpl.clientEmail,
        phone: tpl.clientPhone,
        isSEZ: tpl.isSEZ,
      },
      details: {
        invoiceNumber,
        invoiceDate: today,
        dueDate,
        placeOfSupply: tpl.placeOfSupply || '',
      },
      items: (tpl.items || []).map((i: Rec) => ({ ...i, name: i.name || i.description || '' })),
      totals,
      invoiceType: type,
      customTerms: tpl.customTerms || '',
      customNotes: tpl.customNotes || '',
      extraSections: tpl.extraSections || [],
      invoiceOptions: tpl.invoiceOptions || {},
      taxInclusive: !!tpl.taxInclusive,
    },
  };
  await putDoc(tx, orgId, 'bills', invoiceNumber, bill);

  // Advance the template. The day of month it started on is remembered, so a schedule on the 31st returns to the 31st after February.
  const from = tpl.nextDate || today;
  if (!tpl.anchorDay && tpl.frequency !== 'weekly')
    tpl.anchorDay = Number(from.slice(8, 10)) || undefined;
  tpl.nextDate = advanceDate(from, tpl.frequency, tpl.interval, tpl.anchorDay);
  tpl.lastGenerated = today;
  tpl.occurrencesCreated = (tpl.occurrencesCreated || 0) + 1;
  await putDoc(tx, orgId, 'recurring', String(tpl.id), tpl as Doc);
  return invoiceNumber;
}
